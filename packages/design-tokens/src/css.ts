import { brand, palette, STEPS } from './palette';
import { BASE_TOKENS, baseHue, semantic, type SemanticTheme, STATUS_HUES } from './semantic';

const RADIUS = '0.375rem';

/** Figma type scale (Roboto). Figma uses 100% line height; code uses 1.2 for headings for readability. */
const TYPE_SCALE: ReadonlyArray<[name: string, size: string, weight: number]> = [
  ['display-1', '2.5rem', 800],
  ['display-2', '2rem', 800],
  ['display-3', '1.5rem', 700],
  ['display-4', '1.25rem', 600],
  ['display-5', '1.125rem', 600],
  ['display-6', '1rem', 600],
  ['h1', '1.75rem', 700],
  ['h2', '1.5rem', 700],
  ['h3', '1.25rem', 600],
  ['h4', '1.125rem', 600],
  ['h5', '1rem', 500],
  ['h6', '0.9375rem', 500],
];

/** shadcn variables that are aliases of Classloom tokens rather than values of their own. */
const ALIASES: ReadonlyArray<[name: string, target: string]> = [
  ['sidebar-primary', 'primary'],
  ['sidebar-primary-foreground', 'primary-foreground'],
  ['sidebar-accent', 'accent'],
  ['sidebar-accent-foreground', 'accent-foreground'],
  ['sidebar-border', 'border'],
  ['sidebar-ring', 'ring'],
];

const CHARTS: ReadonlyArray<string> = [
  baseHue.primary,
  baseHue.secondary,
  baseHue.warning,
  baseHue.danger,
  baseHue.violet,
  baseHue.green,
];

const semanticNames = (): string[] => [
  ...BASE_TOKENS,
  ...STATUS_HUES.flatMap((hue) => [`${hue}-tint`, `${hue}-strong`]),
];

function declarations(values: SemanticTheme): string[] {
  return semanticNames().map((name) => `  --${name}: ${values[name as keyof SemanticTheme]};`);
}

/** Builds `tokens.css`: semantic variables for light/dark plus the Tailwind v4 `@theme` mapping. */
export function buildTokensCss(): string {
  const root = [
    ...declarations(semantic.light),
    ...ALIASES.map(([name, target]) => `  --${name}: var(--${target});`),
    ...CHARTS.map((hex, i) => `  --chart-${i + 1}: ${hex};`),
    `  --radius: ${RADIUS};`,
  ];
  const dark = declarations(semantic.dark);

  const theme = [
    ...[...semanticNames(), ...ALIASES.map(([name]) => name)].map(
      (name) => `  --color-${name}: var(--${name});`,
    ),
    ...CHARTS.map((_, i) => `  --color-chart-${i + 1}: var(--chart-${i + 1});`),
    ...Object.entries(brand).map(([name, hex]) => `  --color-brand-${name}: ${hex};`),
    ...Object.entries(palette).flatMap(([rampName, ramp]) =>
      STEPS.map((step) => `  --color-${rampName}-${step}: ${ramp[step]};`),
    ),
    `  --font-sans: var(--font-roboto), 'Roboto', 'Noto Sans Devanagari', ui-sans-serif, system-ui, sans-serif;`,
    '  --radius-sm: calc(var(--radius) - 2px);',
    '  --radius-md: var(--radius);',
    '  --radius-lg: calc(var(--radius) + 2px);',
    '  --radius-xl: calc(var(--radius) + 6px);',
    ...TYPE_SCALE.flatMap(([name, size, weight]) => [
      `  --text-${name}: ${size};`,
      `  --text-${name}--line-height: 1.2;`,
      `  --text-${name}--font-weight: ${weight};`,
    ]),
  ];

  return [
    '/* Generated by src/css.ts from the PreSkool Figma tokens. Do not edit; run `pnpm tokens:css`. */',
    '',
    '@custom-variant dark (&:is(.dark *));',
    '',
    ':root {',
    ...root,
    '}',
    '',
    '.dark {',
    ...dark,
    '}',
    '',
    '@theme inline {',
    ...theme,
    '}',
    '',
  ].join('\n');
}
